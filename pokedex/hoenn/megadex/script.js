/* =========================================================
   ÉTAT
   ========================================================= */

const STORAGE_KEY =
  "hoennMegadexState";


let state =
  JSON.parse(
    localStorage.getItem(
      STORAGE_KEY
    ) || "{}"
  );


let currentFilter =
  "all";


/* =========================================================
   SAUVEGARDE
   ========================================================= */

function save() {

  localStorage.setItem(
    STORAGE_KEY,
    JSON.stringify(state)
  );

}


/* =========================================================
   PROGRESSION
   ========================================================= */

function updateProgress() {

  const total =
    MEGADEX.length;

  const obtained =
    MEGADEX.filter(
      pokemon =>
        state[pokemon.id] === true
    ).length;


  const percent =
    total === 0
      ? 0
      : Math.round(
          obtained / total * 100
        );


  document.getElementById(
    "progressText"
  ).textContent =
    `${obtained} / ${total}`;


  document.getElementById(
    "progressPercent"
  ).textContent =
    `${percent}%`;


  document.getElementById(
    "progressBar"
  ).style.width =
    `${percent}%`;

}


/* =========================================================
   AFFICHAGE
   ========================================================= */

function render() {

  const container =
    document.getElementById(
      "pokemonList"
    );


  container.innerHTML = "";


  const search =
    document.getElementById(
      "search"
    ).value
      .toLowerCase()
      .trim();


  const filtered =
    MEGADEX.filter(
      pokemon => {


        /*
         * Recherche
         */

        if (
          search &&
          !pokemon.name
            .toLowerCase()
            .includes(search)
        ) {

          return false;

        }


        /*
         * Filtre
         */

        if (
          currentFilter === "mega" &&
          pokemon.category !== "mega"
        ) {

          return false;

        }


        if (
          currentFilter === "primal" &&
          pokemon.category !== "primal"
        ) {

          return false;

        }


        if (
          currentFilter === "obtained" &&
          state[pokemon.id] !== true
        ) {

          return false;

        }


        return true;

      }
    );


  /* =======================================================
     CARTES
     ======================================================= */

  filtered.forEach(
    pokemon => {

      const card =
        document.createElement(
          "article"
        );


      card.className =
        "pokemon-card";


      if (
        state[pokemon.id]
      ) {

        card.classList.add(
          "obtained"
        );

      }


      /* ---------------------------------------------------
         Image
         --------------------------------------------------- */

      const image =
        document.createElement(
          "img"
        );


      image.className =
        "pokemon-image";


      image.src =
        pokemon.normal;


      image.alt =
        pokemon.name;


      image.onerror = () => {

        /*
         * On essaye le shiny
         * uniquement si le sprite
         * normal est indisponible.
         */

        image.src =
          pokemon.shiny;

      };


      /* ---------------------------------------------------
         Nom
         --------------------------------------------------- */

      const name =
        document.createElement(
          "div"
        );


      name.className =
        "pokemon-name";


      name.textContent =
        pokemon.name;


      /* ---------------------------------------------------
         Type
         --------------------------------------------------- */

      const type =
        document.createElement(
          "div"
        );


      type.className =
        "pokemon-type";


      type.textContent =
        pokemon.type;


      /* ---------------------------------------------------
         Bouton
         --------------------------------------------------- */

      const button =
        document.createElement(
          "button"
        );


      button.className =
        "obtain-button";


      button.textContent =
        state[pokemon.id]
          ? "✓ Obtenue"
          : "○ Non obtenue";


      button.addEventListener(
        "click",
        () => {

          state[pokemon.id] =
            !state[pokemon.id];


          save();

          render();

          updateProgress();


          if (
            window.pokedexSound &&
            typeof window.pokedexSound.click ===
            "function"
          ) {

            window.pokedexSound.click();

          }

        }
      );


      /* ---------------------------------------------------
         Assemblage
         --------------------------------------------------- */

      card.appendChild(
        image
      );

      card.appendChild(
        name
      );

      card.appendChild(
        type
      );

      card.appendChild(
        button
      );


      container.appendChild(
        card
      );

    }
  );


  updateProgress();

}


/* =========================================================
   RECHERCHE
   ========================================================= */

document
  .getElementById("search")
  .addEventListener(
    "input",
    render
  );


/* =========================================================
   FILTRES
   ========================================================= */

document
  .querySelectorAll(".filter")
  .forEach(
    button => {

      button.addEventListener(
        "click",
        () => {

          document
            .querySelectorAll(
              ".filter"
            )
            .forEach(
              item =>
                item.classList.remove(
                  "active"
                )
            );


          button.classList.add(
            "active"
          );


          currentFilter =
            button.dataset.filter;


          render();

        }
      );

    }
  );


/* =========================================================
   FOND POKÉMON
   ========================================================= */

function createBackground() {

  const container =
    document.getElementById(
      "pokemonBackground"
    );


  if (!container) return;


  container.innerHTML = "";


  /*
   * On prend les formes du Mégadex.
   */

  const pool =
    [...MEGADEX];


  /*
   * Mélange
   */

  for (
    let i = pool.length - 1;
    i > 0;
    i--
  ) {

    const j =
      Math.floor(
        Math.random() *
        (i + 1)
      );


    [
      pool[i],
      pool[j]
    ] = [
      pool[j],
      pool[i]
    ];

  }


  /*
   * Toutes les formes ne sont
   * pas forcément affichées.
   */

  const amount =
    window.innerWidth <= 600
      ? 18
      : 28;


  const positions = [];


  for (
    const pokemon of pool
  ) {

    if (
      positions.length >= amount
    ) {

      break;

    }


    let x;
    let y;

    let valid = false;

    let tries = 0;


    while (
      !valid &&
      tries < 300
    ) {

      x =
        5 +
        Math.random() * 90;

      y =
        5 +
        Math.random() * 90;


      valid =
        positions.every(
          position => {

            const dx =
              position.x - x;

            const dy =
              position.y - y;


            return Math.sqrt(
              dx * dx +
              dy * dy
            ) > 13;

          }
        );


      tries++;

    }


    if (!valid) continue;


    positions.push({
      x,
      y
    });


    const image =
      document.createElement(
        "img"
      );


    image.className =
      "bg-pokemon";


    image.src =
      Math.random() < 0.12
        ? pokemon.shiny
        : pokemon.normal;


    image.alt = "";


    image.style.left =
      `${x}%`;


    image.style.top =
      `${y}%`;


    const size =
      45 +
      Math.random() * 35;


    image.style.width =
      `${size}px`;


    image.style.height =
      `${size}px`;


    image.style.setProperty(
      "--rotation",
      `${-8 + Math.random() * 16}deg`
    );


    image.style.setProperty(
      "--duration",
      `${7 + Math.random() * 8}s`
    );


    image.style.setProperty(
      "--delay",
      `${Math.random() * -10}s`
    );


    image.onerror =
      () => image.remove();


    container.appendChild(
      image
    );

  }

}


/* =========================================================
   LANCEMENT
   ========================================================= */

createBackground();

render();
updateProgress();
